IF COL_LENGTH(N'dbo.TINTUCHOCTHUAT', N'MaHD') IS NOT NULL
BEGIN
  IF EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_TIN_HOATDONG')
    ALTER TABLE dbo.TINTUCHOCTHUAT DROP CONSTRAINT FK_TIN_HOATDONG;

  DECLARE @activityType sysname;
  SELECT @activityType=TYPE_NAME(user_type_id) FROM sys.columns WHERE object_id=OBJECT_ID(N'dbo.HOATDONGHOCTHUAT') AND name=N'MaHD';
  EXEC('ALTER TABLE dbo.TINTUCHOCTHUAT ALTER COLUMN MaHD ' + @activityType + ' NULL;');

  ALTER TABLE dbo.TINTUCHOCTHUAT ADD CONSTRAINT FK_TIN_HOATDONG FOREIGN KEY (MaHD) REFERENCES dbo.HOATDONGHOCTHUAT(MaHD);
END;
