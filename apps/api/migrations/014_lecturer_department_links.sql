-- Keep the API's multi-department lecturer assignments compatible with the SQL import.
IF OBJECT_ID(N'dbo.GIANGVIEN_BOMON', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.GIANGVIEN_BOMON (
    MaGV INT NOT NULL,
    MaBM INT NOT NULL,
    VaiTro NVARCHAR(50) NOT NULL CONSTRAINT DF_GIANGVIEN_BOMON_VAITRO DEFAULT N'Phụ trách',
    CONSTRAINT PK_GIANGVIEN_BOMON PRIMARY KEY (MaGV, MaBM),
    CONSTRAINT FK_GVBM_GIANGVIEN FOREIGN KEY (MaGV) REFERENCES dbo.GIANGVIEN(MaGV) ON DELETE CASCADE,
    CONSTRAINT FK_GVBM_BOMON FOREIGN KEY (MaBM) REFERENCES dbo.BOMON(MaBM) ON DELETE CASCADE
  );
END
GO
INSERT INTO dbo.GIANGVIEN_BOMON(MaGV,MaBM,VaiTro)
SELECT gv.MaGV,gv.MaBM,N'Phụ trách'
FROM dbo.GIANGVIEN gv
WHERE gv.MaBM IS NOT NULL
  AND NOT EXISTS(SELECT 1 FROM dbo.GIANGVIEN_BOMON link WHERE link.MaGV=gv.MaGV AND link.MaBM=gv.MaBM);
GO
