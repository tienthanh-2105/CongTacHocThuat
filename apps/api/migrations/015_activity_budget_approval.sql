-- Per-activity estimate proposal and faculty approval.
-- Supports both the supplied 40-table schema (INT keys) and the API schema (BIGINT keys).

IF OBJECT_ID(N'dbo.DUTRUKINHPHI', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.DUTRUKINHPHI (
    MaDuTruKP BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaHD BIGINT NULL,
    TenTieuDe NVARCHAR(250) NOT NULL,
    NamHoc NVARCHAR(20) NOT NULL,
    TongKinhPhi DECIMAL(18,2) NOT NULL CONSTRAINT DF_DUTRUKINHPHI_TONG DEFAULT 0,
    NguoiLap BIGINT NOT NULL,
    NgayLap DATETIME2 NOT NULL CONSTRAINT DF_DUTRUKINHPHI_NGAYLAP DEFAULT SYSDATETIME(),
    NguoiDuyet BIGINT NULL,
    NgayDuyet DATETIME2 NULL,
    TrangThai NVARCHAR(30) NOT NULL CONSTRAINT DF_DUTRUKINHPHI_TRANGTHAI DEFAULT N'Dự thảo',
    GhiChuDuyet NVARCHAR(500) NULL,
    CONSTRAINT FK_DUTRUKINHPHI_TAIKHOAN_LAP FOREIGN KEY (NguoiLap) REFERENCES dbo.TAIKHOAN(MaTK),
    CONSTRAINT FK_DUTRUKINHPHI_TAIKHOAN_DUYET FOREIGN KEY (NguoiDuyet) REFERENCES dbo.TAIKHOAN(MaTK),
    CONSTRAINT FK_DUTRUKINHPHI_HOATDONG FOREIGN KEY (MaHD) REFERENCES dbo.HOATDONGHOCTHUAT(MaHD),
    CONSTRAINT CK_DUTRUKINHPHI_TRANGTHAI CHECK (TrangThai IN (N'Dự thảo', N'Chờ duyệt', N'Đã duyệt', N'Từ chối'))
  );
END;
GO

IF COL_LENGTH(N'dbo.DUTRUKINHPHI', N'MaHD') IS NULL
BEGIN
  DECLARE @activityKeyType sysname;
  SELECT @activityKeyType = TYPE_NAME(c.user_type_id)
  FROM sys.columns c
  WHERE c.object_id = OBJECT_ID(N'dbo.HOATDONGHOCTHUAT') AND c.name = N'MaHD';
  IF @activityKeyType NOT IN (N'int', N'bigint')
    THROW 51010, 'HOATDONGHOCTHUAT.MaHD must be int or bigint to link budget proposals.', 1;
  EXEC(N'ALTER TABLE dbo.DUTRUKINHPHI ADD MaHD ' + @activityKeyType + N' NULL;');
END;
GO

IF COL_LENGTH(N'dbo.DUTRUKINHPHI', N'GhiChuDuyet') IS NULL
  ALTER TABLE dbo.DUTRUKINHPHI ADD GhiChuDuyet NVARCHAR(500) NULL;
GO

IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_DUTRUKINHPHI_HOATDONG')
  ALTER TABLE dbo.DUTRUKINHPHI ADD CONSTRAINT FK_DUTRUKINHPHI_HOATDONG
    FOREIGN KEY (MaHD) REFERENCES dbo.HOATDONGHOCTHUAT(MaHD);
GO

IF OBJECT_ID(N'dbo.KINHPHIHOATDONG', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.KINHPHIHOATDONG (
    MaKPHD BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaDuTruKP BIGINT NULL,
    MaHD BIGINT NOT NULL,
    NoiDung NVARCHAR(MAX) NOT NULL,
    SoLuong DECIMAL(10,2) NULL,
    DonViTinh NVARCHAR(50) NULL,
    DonGia DECIMAL(18,2) NULL,
    SoTien DECIMAL(18,2) NOT NULL CONSTRAINT DF_KINHPHIHOATDONG_SOTIEN DEFAULT 0,
    ThuyetMinh NVARCHAR(500) NULL,
    NguonKinhPhi NVARCHAR(100) NOT NULL CONSTRAINT DF_KINHPHIHOATDONG_NGUON DEFAULT N'Kinh phí học thuật',
    GhiChu NVARCHAR(500) NULL,
    CONSTRAINT FK_KINHPHIHOATDONG_DUTRU FOREIGN KEY (MaDuTruKP) REFERENCES dbo.DUTRUKINHPHI(MaDuTruKP) ON DELETE CASCADE,
    CONSTRAINT FK_KINHPHIHOATDONG_HOATDONG FOREIGN KEY (MaHD) REFERENCES dbo.HOATDONGHOCTHUAT(MaHD),
    CONSTRAINT CK_KINHPHIHOATDONG_SOTIEN CHECK (SoTien >= 0)
  );
END;
GO

-- Older copies of the supplied schema require every line to be attached to a header.
-- Allow drafts to be entered first, then attach them when the activity is submitted.
IF COL_LENGTH(N'dbo.KINHPHIHOATDONG', N'MaDuTruKP') IS NOT NULL
  AND EXISTS (
    SELECT 1 FROM sys.columns
    WHERE object_id = OBJECT_ID(N'dbo.KINHPHIHOATDONG') AND name = N'MaDuTruKP' AND is_nullable = 0
  )
BEGIN
  DECLARE @proposalKeyType sysname;
  SELECT @proposalKeyType = TYPE_NAME(c.user_type_id)
  FROM sys.columns c
  WHERE c.object_id = OBJECT_ID(N'dbo.DUTRUKINHPHI') AND c.name = N'MaDuTruKP';
  IF @proposalKeyType NOT IN (N'int', N'bigint')
    THROW 51011, 'DUTRUKINHPHI.MaDuTruKP must be int or bigint.', 1;
  EXEC(N'ALTER TABLE dbo.KINHPHIHOATDONG ALTER COLUMN MaDuTruKP ' + @proposalKeyType + N' NULL;');
END;
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.DUTRUKINHPHI') AND name = N'IX_DUTRUKINHPHI_ACTIVITY_STATUS')
  CREATE INDEX IX_DUTRUKINHPHI_ACTIVITY_STATUS ON dbo.DUTRUKINHPHI(MaHD, TrangThai);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.KINHPHIHOATDONG') AND name = N'IX_KINHPHIHOATDONG_ACTIVITY_PROPOSAL')
  CREATE INDEX IX_KINHPHIHOATDONG_ACTIVITY_PROPOSAL ON dbo.KINHPHIHOATDONG(MaHD, MaDuTruKP);
GO

-- Link older estimate headers to their activity when every detail belongs to one activity.
;WITH ActivityPerProposal AS (
  SELECT MaDuTruKP, MIN(MaHD) AS MaHD, COUNT(DISTINCT MaHD) AS ActivityCount
  FROM dbo.KINHPHIHOATDONG
  WHERE MaDuTruKP IS NOT NULL
  GROUP BY MaDuTruKP
)
UPDATE d
SET MaHD = a.MaHD
FROM dbo.DUTRUKINHPHI d
JOIN ActivityPerProposal a ON a.MaDuTruKP = d.MaDuTruKP AND a.ActivityCount = 1
WHERE d.MaHD IS NULL;
GO
