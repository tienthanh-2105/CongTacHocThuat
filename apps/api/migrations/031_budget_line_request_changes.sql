  SELECT 1 FROM sys.check_constraints
  WHERE parent_object_id=OBJECT_ID(N'dbo.KINHPHIHOATDONG')
    AND name=N'CK_KINHPHIHOATDONG_TRANGTHAI'
)
  ALTER TABLE dbo.KINHPHIHOATDONG DROP CONSTRAINT CK_KINHPHIHOATDONG_TRANGTHAI;

