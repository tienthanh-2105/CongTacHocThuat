-- Keep key types compatible with both the original and legacy SQL Server schemas.
DECLARE @departmentType NVARCHAR(128) = (SELECT TYPE_NAME(system_type_id) FROM sys.columns WHERE object_id=OBJECT_ID(N'dbo.BOMON') AND name=N'MaBM');
DECLARE @accountType NVARCHAR(128) = (SELECT TYPE_NAME(system_type_id) FROM sys.columns WHERE object_id=OBJECT_ID(N'dbo.TAIKHOAN') AND name=N'MaTK');
IF OBJECT_ID(N'dbo.PHANCONGDEXUATBOMON', N'U') IS NULL
EXEC(N'CREATE TABLE dbo.PHANCONGDEXUATBOMON (
  MaPhanCongDeXuat INT IDENTITY PRIMARY KEY,
  MaBM '+@departmentType+N' NOT NULL REFERENCES dbo.BOMON(MaBM),
  NguoiGiao '+@accountType+N' NOT NULL REFERENCES dbo.TAIKHOAN(MaTK),
  NguoiChuTri '+@accountType+N' NOT NULL REFERENCES dbo.TAIKHOAN(MaTK),
  TenHoatDong NVARCHAR(200) NOT NULL,
  LoaiHoatDong NVARCHAR(20) NOT NULL CHECK (LoaiHoatDong IN (N''Cuộc thi'',N''Seminar'')),
  NamHoc NVARCHAR(20) NOT NULL,
  NoiDung NVARCHAR(MAX) NOT NULL,
  HanHoanThanh DATE NOT NULL,
  NgayGiao DATETIMEOFFSET NOT NULL DEFAULT SYSDATETIMEOFFSET()
);');
IF OBJECT_ID(N'dbo.NGUOITHUCHIENDEXUAT', N'U') IS NULL
EXEC(N'CREATE TABLE dbo.NGUOITHUCHIENDEXUAT (
  MaPhanCongDeXuat INT NOT NULL REFERENCES dbo.PHANCONGDEXUATBOMON(MaPhanCongDeXuat),
  MaTK '+@accountType+N' NOT NULL REFERENCES dbo.TAIKHOAN(MaTK),
  PRIMARY KEY(MaPhanCongDeXuat,MaTK)
);');
GO
IF COL_LENGTH(N'dbo.THONGBAO',N'MaPhanCongDeXuat') IS NULL
  ALTER TABLE dbo.THONGBAO ADD MaPhanCongDeXuat INT NULL
    CONSTRAINT FK_THONGBAO_PHANCONGDEXUAT REFERENCES dbo.PHANCONGDEXUATBOMON(MaPhanCongDeXuat);
GO
