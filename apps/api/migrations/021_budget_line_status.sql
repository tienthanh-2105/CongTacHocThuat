IF COL_LENGTH(N'dbo.KINHPHIHOATDONG', N'TrangThai') IS NULL
BEGIN
  ALTER TABLE dbo.KINHPHIHOATDONG ADD TrangThai NVARCHAR(30) NULL;
  UPDATE line
    SET TrangThai = COALESCE(proposal.TrangThai, N'Dự thảo')
  FROM dbo.KINHPHIHOATDONG line
  LEFT JOIN dbo.DUTRUKINHPHI proposal ON proposal.MaDuTruKP = line.MaDuTruKP;
  ALTER TABLE dbo.KINHPHIHOATDONG ALTER COLUMN TrangThai NVARCHAR(30) NOT NULL;
END;
GO
IF NOT EXISTS (SELECT 1 FROM sys.default_constraints WHERE parent_object_id=OBJECT_ID(N'dbo.KINHPHIHOATDONG') AND name=N'DF_KINHPHIHOATDONG_TRANGTHAI')
  ALTER TABLE dbo.KINHPHIHOATDONG ADD CONSTRAINT DF_KINHPHIHOATDONG_TRANGTHAI DEFAULT N'Dự thảo' FOR TrangThai;
GO
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID(N'dbo.KINHPHIHOATDONG') AND name=N'CK_KINHPHIHOATDONG_TRANGTHAI')
  ALTER TABLE dbo.KINHPHIHOATDONG ADD CONSTRAINT CK_KINHPHIHOATDONG_TRANGTHAI CHECK (TrangThai IN (N'Dự thảo',N'Chờ duyệt',N'Đã duyệt',N'Từ chối'));
GO
