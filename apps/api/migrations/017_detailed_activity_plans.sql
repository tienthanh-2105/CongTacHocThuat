-- Department implementation plans signed by the faculty and Student Affairs.
-- Preserve the imported INT schema and the API's BIGINT schema.
IF OBJECT_ID(N'dbo.KEHOACHTOCHUC',N'U') IS NULL
BEGIN
  DECLARE @activityType sysname, @planType sysname, @departmentType sysname, @accountType sysname;
  SELECT @activityType=TYPE_NAME(user_type_id) FROM sys.columns WHERE object_id=OBJECT_ID(N'dbo.HOATDONGHOCTHUAT') AND name=N'MaHD';
  SELECT @planType=TYPE_NAME(user_type_id) FROM sys.columns WHERE object_id=OBJECT_ID(N'dbo.KEHOACHHOCTHUAT') AND name=N'MaKeHoach';
  SELECT @departmentType=TYPE_NAME(user_type_id) FROM sys.columns WHERE object_id=OBJECT_ID(N'dbo.BOMON') AND name=N'MaBM';
  SELECT @accountType=TYPE_NAME(user_type_id) FROM sys.columns WHERE object_id=OBJECT_ID(N'dbo.TAIKHOAN') AND name=N'MaTK';
  IF COALESCE(@activityType,N'') NOT IN(N'int',N'bigint') OR COALESCE(@planType,N'') NOT IN(N'int',N'bigint')
    OR COALESCE(@departmentType,N'') NOT IN(N'int',N'bigint') OR COALESCE(@accountType,N'') NOT IN(N'int',N'bigint')
    THROW 51017,'Detailed plans require int or bigint activity, annual-plan, department and account keys.',1;
  EXEC(N'CREATE TABLE dbo.KEHOACHTOCHUC (
    MaKHToChuc BIGINT IDENTITY PRIMARY KEY,
    MaHD '+@activityType+N' NOT NULL,
    MaKeHoach '+@planType+N' NOT NULL,
    MaBM '+@departmentType+N' NOT NULL,
    TenKeHoach NVARCHAR(250) NOT NULL, NoiDung NVARCHAR(MAX) NOT NULL,
    TheLe NVARCHAR(MAX) NULL, TieuChiCham NVARCHAR(MAX) NULL,
    HinhThucThi NVARCHAR(30) NOT NULL CONSTRAINT DF_KHTC_HINHTHUC DEFAULT N''Cá nhân'',
    ThoiGianBatDau DATETIME2 NOT NULL, ThoiGianKetThuc DATETIME2 NOT NULL, HanDangKy DATETIME2 NULL,
    DiaDiem NVARCHAR(255) NULL,
    DiemRenLuyen DECIMAL(5,2) NOT NULL CONSTRAINT DF_KHTC_DRL DEFAULT 5,
    TrangThai NVARCHAR(30) NOT NULL CONSTRAINT DF_KHTC_TRANGTHAI DEFAULT N''Dự thảo'',
    NguoiLap '+@accountType+N' NOT NULL,
    NguoiKyKhoa '+@accountType+N' NULL, NgayKyKhoa DATETIMEOFFSET NULL,
    NguoiKyCTSV '+@accountType+N' NULL, NgayKyCTSV DATETIMEOFFSET NULL,
    LichSuDuyet NVARCHAR(MAX) NOT NULL CONSTRAINT DF_KHTC_LICHSU DEFAULT N''[]'',
    CongBoLuc DATETIMEOFFSET NULL,
    CONSTRAINT UQ_KHTC_HOATDONG UNIQUE(MaHD),
    CONSTRAINT FK_KHTC_HOATDONG FOREIGN KEY(MaHD) REFERENCES dbo.HOATDONGHOCTHUAT(MaHD),
    CONSTRAINT FK_KHTC_KEHOACH FOREIGN KEY(MaKeHoach) REFERENCES dbo.KEHOACHHOCTHUAT(MaKeHoach),
    CONSTRAINT FK_KHTC_BOMON FOREIGN KEY(MaBM) REFERENCES dbo.BOMON(MaBM),
    CONSTRAINT FK_KHTC_NGUOILAP FOREIGN KEY(NguoiLap) REFERENCES dbo.TAIKHOAN(MaTK),
    CONSTRAINT FK_KHTC_KYKHOA FOREIGN KEY(NguoiKyKhoa) REFERENCES dbo.TAIKHOAN(MaTK),
    CONSTRAINT FK_KHTC_KYCTSV FOREIGN KEY(NguoiKyCTSV) REFERENCES dbo.TAIKHOAN(MaTK),
    CONSTRAINT CK_KHTC_TRANGTHAI CHECK(TrangThai IN(N''Dự thảo'',N''Chờ khoa ký'',N''Chờ CTSV ký'',N''Đã duyệt'',N''Cần bổ sung'',N''Từ chối'')),
    CONSTRAINT CK_KHTC_HINHTHUC CHECK(HinhThucThi IN(N''Cá nhân'',N''Theo đội'')),
    CONSTRAINT CK_KHTC_THOIGIAN CHECK(ThoiGianKetThuc>ThoiGianBatDau AND (HanDangKy IS NULL OR HanDangKy<=ThoiGianBatDau)),
    CONSTRAINT CK_KHTC_DRL CHECK(DiemRenLuyen BETWEEN 0 AND 100),
    CONSTRAINT CK_KHTC_LICHSU CHECK(ISJSON(LichSuDuyet)>0)
  );');
END;
GO
