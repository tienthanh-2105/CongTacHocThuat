CREATE OR ALTER TRIGGER dbo.trg_ChiPhiKhongVuotDuToan
ON dbo.CHIPHITHUCTE
AFTER INSERT, UPDATE
AS
BEGIN
  SET NOCOUNT ON;
  IF EXISTS (
    SELECT i.MaHD FROM inserted i JOIN dbo.HOATDONGHOCTHUAT h ON h.MaHD=i.MaHD
    WHERE h.KinhPhiDuTru > 0
    GROUP BY i.MaHD,h.KinhPhiDuTru
    HAVING (SELECT SUM(c.SoTien) FROM dbo.CHIPHITHUCTE c WHERE c.MaHD=i.MaHD) > h.KinhPhiDuTru
  ) THROW 51001, N'Tổng chi phí thực tế vượt dự toán của hoạt động.', 1;
END;
