IF COL_LENGTH(N'dbo.SEMINAR', N'DaDangThongBao') IS NULL
  ALTER TABLE dbo.SEMINAR ADD DaDangThongBao BIT NOT NULL
    CONSTRAINT DF_SEMINAR_DADANGTHONGBAO DEFAULT (0);
GO

UPDATE s SET DaDangThongBao = 1
FROM dbo.SEMINAR s
WHERE s.DaDangThongBao = 0 AND EXISTS (
  SELECT 1 FROM dbo.TINTUCHOCTHUAT n
  WHERE n.MaHD = s.MaHD AND n.CongBoLuc IS NOT NULL
);
