  TgBatDau=COALESCE(h.TgBatDau,TRY_CONVERT(DATETIME2,LEFT(LTRIM(h.TgDuKien),10),103),s.ThoiGian,c.ThoiGian),
  TgKetThuc=COALESCE(h.TgKetThuc,DATEADD(HOUR,2,TRY_CONVERT(DATETIME2,LEFT(LTRIM(h.TgDuKien),10),103)),DATEADD(HOUR,2,s.ThoiGian),DATEADD(HOUR,2,c.ThoiGian)),
  KinhPhiDuTru=CASE WHEN h.KinhPhiDuTru=0 THEN COALESCE(kp.TongDuToan,0) ELSE h.KinhPhiDuTru END
FROM dbo.HOATDONGHOCTHUAT h
LEFT JOIN dbo.SEMINAR s ON s.MaHD=h.MaHD
LEFT JOIN dbo.CUOCTHI c ON c.MaHD=h.MaHD
OUTER APPLY(SELECT SUM(SoTien) AS TongDuToan FROM dbo.KINHPHIHOATDONG x WHERE x.MaHD=h.MaHD) kp;
