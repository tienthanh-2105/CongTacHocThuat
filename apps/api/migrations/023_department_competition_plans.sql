IF OBJECT_ID(N'dbo.KEHOACHCUOCTHIBOMON', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.KEHOACHCUOCTHIBOMON (
    MaDeXuat INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaBM INT NOT NULL,
    NamHoc NVARCHAR(20) NOT NULL,
    TenCuocThi NVARCHAR(200) NOT NULL,
    NoiDung NVARCHAR(MAX) NOT NULL,
    DuTruKinhPhi DECIMAL(18,2) NOT NULL CONSTRAINT DF_KHCTBM_KINHPHI DEFAULT 0,
    NguoiLap INT NOT NULL,
    TrangThai NVARCHAR(30) NOT NULL CONSTRAINT DF_KHCTBM_TRANGTHAI DEFAULT N'Dự thảo',
    GhiChuDuyet NVARCHAR(1000) NULL,
    MaKeHoachKhoa INT NULL,
    NgayTao DATETIMEOFFSET NOT NULL CONSTRAINT DF_KHCTBM_NGAYTAO DEFAULT SYSDATETIMEOFFSET(),
    NgayCapNhat DATETIMEOFFSET NOT NULL CONSTRAINT DF_KHCTBM_NGAYCAPNHAT DEFAULT SYSDATETIMEOFFSET(),
    CONSTRAINT FK_KHCTBM_BOMON FOREIGN KEY (MaBM) REFERENCES dbo.BOMON(MaBM),
    CONSTRAINT FK_KHCTBM_NGUOILAP FOREIGN KEY (NguoiLap) REFERENCES dbo.TAIKHOAN(MaTK),
    CONSTRAINT FK_KHCTBM_KEHOACH FOREIGN KEY (MaKeHoachKhoa) REFERENCES dbo.KEHOACHHOCTHUAT(MaKeHoach),
    CONSTRAINT CK_KHCTBM_TRANGTHAI CHECK (TrangThai IN (N'Dự thảo',N'Chờ Trưởng bộ môn',N'Cần bổ sung',N'Chờ khoa',N'Đã duyệt',N'Khoa yêu cầu bổ sung')),
    CONSTRAINT CK_KHCTBM_KINHPHI CHECK (DuTruKinhPhi >= 0)
  );
  CREATE INDEX IX_KHCTBM_BOMON_NAMHOC ON dbo.KEHOACHCUOCTHIBOMON(MaBM,NamHoc,TrangThai);
END;

