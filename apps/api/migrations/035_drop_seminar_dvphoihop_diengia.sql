-- 035_drop_seminar_dvphoihop_diengia.sql
IF EXISTS (SELECT 1 FROM sys.default_constraints WHERE name = 'DF_LEGACY_SEMINAR_DIENGIA')
BEGIN
    ALTER TABLE SEMINAR DROP CONSTRAINT DF_LEGACY_SEMINAR_DIENGIA;
END;

IF EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'SEMINAR' AND COLUMN_NAME = 'DVPhoiHop')
BEGIN
    ALTER TABLE SEMINAR DROP COLUMN DVPhoiHop;
END;

IF EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'SEMINAR' AND COLUMN_NAME = 'DienGia')
BEGIN
    ALTER TABLE SEMINAR DROP COLUMN DienGia;
END;
