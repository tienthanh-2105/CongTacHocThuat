IF OBJECT_ID(N'dbo.FCM_DEVICE', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.FCM_DEVICE (
    Token NVARCHAR(500) NOT NULL CONSTRAINT PK_FCM_DEVICE PRIMARY KEY,
    MaTK BIGINT NOT NULL,
    NenTang NVARCHAR(20) NOT NULL CONSTRAINT DF_FCM_DEVICE_NenTang DEFAULT N'android',
    CapNhatLuc DATETIMEOFFSET NOT NULL CONSTRAINT DF_FCM_DEVICE_CapNhatLuc DEFAULT SYSDATETIMEOFFSET()
  );
  CREATE INDEX IX_FCM_DEVICE_MaTK ON dbo.FCM_DEVICE(MaTK);
END
GO

IF OBJECT_ID(N'dbo.FCM_NOTIFICATION_QUEUE', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.FCM_NOTIFICATION_QUEUE (
    MaThongBao BIGINT NOT NULL CONSTRAINT PK_FCM_NOTIFICATION_QUEUE PRIMARY KEY,
    MaTK BIGINT NOT NULL,
    TrangThai NVARCHAR(20) NOT NULL CONSTRAINT DF_FCM_PUSH_TrangThai DEFAULT N'Cho gui',
    SoLanThu TINYINT NOT NULL CONSTRAINT DF_FCM_PUSH_SoLanThu DEFAULT 0,
    TaoLuc DATETIMEOFFSET NOT NULL CONSTRAINT DF_FCM_PUSH_TaoLuc DEFAULT SYSDATETIMEOFFSET(),
    GuiLuc DATETIMEOFFSET NULL,
    Loi NVARCHAR(1000) NULL
  );
  CREATE INDEX IX_FCM_QUEUE_Status ON dbo.FCM_NOTIFICATION_QUEUE(TrangThai, TaoLuc);
END
GO

CREATE OR ALTER TRIGGER dbo.TR_THONGBAO_QUEUE_FCM
ON dbo.THONGBAO
AFTER INSERT
AS
BEGIN
  SET NOCOUNT ON;
  INSERT INTO dbo.FCM_NOTIFICATION_QUEUE(MaThongBao, MaTK)
  SELECT i.MaThongBao, i.MaTK
  FROM inserted i
  WHERE EXISTS (SELECT 1 FROM dbo.FCM_DEVICE d WHERE d.MaTK = i.MaTK);
END
GO
