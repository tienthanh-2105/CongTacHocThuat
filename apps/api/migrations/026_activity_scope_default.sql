IF OBJECT_ID(N'dbo.KEHOACHHOCTHUAT_HOATDONG', N'U') IS NOT NULL
  DROP TABLE dbo.KEHOACHHOCTHUAT_HOATDONG;

IF COL_LENGTH(N'dbo.HOATDONGHOCTHUAT', N'CapTC') IS NULL
BEGIN
  ALTER TABLE dbo.HOATDONGHOCTHUAT
    ADD CapTC NVARCHAR(50) NOT NULL
      CONSTRAINT DF_HOATDONGHOCTHUAT_CapTC DEFAULT N'Cấp Khoa' WITH VALUES;
END
ELSE
BEGIN
  EXEC sys.sp_executesql N'UPDATE dbo.HOATDONGHOCTHUAT SET CapTC=N''Cấp Khoa'' WHERE CapTC IS NULL';
  IF NOT EXISTS (
    SELECT 1 FROM sys.default_constraints dc
    JOIN sys.columns c ON c.object_id=dc.parent_object_id AND c.column_id=dc.parent_column_id
    WHERE dc.parent_object_id=OBJECT_ID(N'dbo.HOATDONGHOCTHUAT') AND c.name=N'CapTC'
  )
    ALTER TABLE dbo.HOATDONGHOCTHUAT
      ADD CONSTRAINT DF_HOATDONGHOCTHUAT_CapTC DEFAULT N'Cấp Khoa' FOR CapTC;
END;
