  MaVong BIGINT NOT NULL, MaTK BIGINT NOT NULL, VaiTro VARCHAR(20) NOT NULL,
  NguoiPhanCong BIGINT NOT NULL, PhanCongLuc DATETIMEOFFSET NOT NULL DEFAULT SYSDATETIMEOFFSET(),
  CONSTRAINT PK_PHANCONGVONGTHI PRIMARY KEY(MaVong,MaTK,VaiTro),
  CONSTRAINT CK_PHANCONGVONGTHI_ROLE CHECK(VaiTro IN('RA_DE','CHAM_THI'))
