-- BỔ SUNG THUỘC TÍNH VÀ RÀNG BUỘC
ALTER TABLE GIANGVIEN ADD COLUMN MaBM BIGINT REFERENCES BOMON(MaBM);
ALTER TABLE KEHOACHHOCTHUAT ADD COLUMN MaBM BIGINT REFERENCES BOMON(MaBM);
ALTER TABLE KEHOACHHOCTHUAT ADD COLUMN LoaiKeHoach VARCHAR(20)
    NOT NULL DEFAULT 'KHOA' CHECK(LoaiKeHoach IN ('KHOA','BO_MON'));
ALTER TABLE KEHOACHHOCTHUAT ADD CONSTRAINT CK_KEHOACH_BOMON
    CHECK(LoaiKeHoach <> 'BO_MON' OR MaBM IS NOT NULL);
ALTER TABLE KEHOACHHOCTHUAT ADD COLUMN NguoiDuyet BIGINT REFERENCES TAIKHOAN(MaTK);
ALTER TABLE KEHOACHHOCTHUAT ADD COLUMN NgayDuyet TIMESTAMPTZ;
ALTER TABLE KEHOACHHOCTHUAT ADD COLUMN LichSuDuyet JSONB
    NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(LichSuDuyet)='array');

ALTER TABLE HOATDONGHOCTHUAT ADD COLUMN MaKeHoachKhoa BIGINT
    REFERENCES KEHOACHHOCTHUAT(MaKeHoach);
ALTER TABLE HOATDONGHOCTHUAT ADD COLUMN KinhPhiDuTru NUMERIC(18,2)
    NOT NULL DEFAULT 0 CHECK(KinhPhiDuTru>=0);
ALTER TABLE HOATDONGHOCTHUAT ADD COLUMN NoiDungCongBo TEXT;
ALTER TABLE HOATDONGHOCTHUAT ADD COLUMN NgayCongBo TIMESTAMPTZ;

ALTER TABLE SEMINAR ADD COLUMN DienGia JSONB
    NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(DienGia)='array');
ALTER TABLE BANTOCHUC ADD COLUMN NhiemVu JSONB
    NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(NhiemVu)='array');

ALTER TABLE DETAI ADD COLUMN MaDoi BIGINT REFERENCES DOITHI(MaDoi);
ALTER TABLE DETAI ADD CONSTRAINT CK_DETAI_CHUSOHUU
    CHECK(NOT(MaDoi IS NOT NULL AND MaDK IS NOT NULL));
ALTER TABLE KETQUAHOCTHUAT ADD COLUMN MaDoi BIGINT REFERENCES DOITHI(MaDoi);
ALTER TABLE KETQUAHOCTHUAT ALTER COLUMN MaDK DROP NOT NULL;
ALTER TABLE KETQUAHOCTHUAT ADD CONSTRAINT CK_DOI_HOAC_CANHAN
    CHECK((MaDoi IS NOT NULL) <> (MaDK IS NOT NULL));

ALTER TABLE DKTHAMGIA DROP CONSTRAINT CK_DK_HINHTHUC;
ALTER TABLE DKTHAMGIA ADD CONSTRAINT CK_DK_HINHTHUC
    CHECK(HinhThuc IN ('Tham gia','Dự thi','Hỗ trợ','Cổ vũ'));
ALTER TABLE DKTHAMGIA ADD COLUMN DaNhacLuc TIMESTAMPTZ;
ALTER TABLE PHANCONGCOVU ADD COLUMN LoaiPhanCong VARCHAR(20)
    NOT NULL DEFAULT 'CO_VU' CHECK(LoaiPhanCong IN ('CO_VU','HO_TRO'));

ALTER TABLE MAQR ADD COLUMN TGMo TIMESTAMPTZ NOT NULL DEFAULT now();
ALTER TABLE MAQR ADD CONSTRAINT CK_QR_THOIGIAN CHECK(TGHetHan>TGMo);
ALTER TABLE CHIPHITHUCTE ADD COLUMN MaHS BIGINT REFERENCES HOSOQUYETTOAN(MaHS);
ALTER TABLE CHIPHITHUCTE ADD COLUMN ChungTu JSONB
    NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(ChungTu)='array');

ALTER TABLE DIEMRENLUYEN DROP CONSTRAINT CK_DRL_SODIEM;
ALTER TABLE DIEMRENLUYEN ADD CONSTRAINT CK_DRL_SODIEM CHECK(SoDiem<>0);
ALTER TABLE DIEMRENLUYEN ADD COLUMN MaDiemGoc BIGINT REFERENCES DIEMRENLUYEN(MaDiem);
ALTER TABLE DIEMRENLUYEN ADD COLUMN NguoiGhi BIGINT REFERENCES TAIKHOAN(MaTK);
ALTER TABLE DIEMRENLUYEN ADD COLUMN GhiLuc TIMESTAMPTZ NOT NULL DEFAULT now();
ALTER TABLE DIEMRENLUYEN ADD CONSTRAINT CK_DIEM_KHONG_TUTHAMCHIEU
    CHECK(MaDiemGoc IS NULL OR MaDiemGoc<>MaDiem);
