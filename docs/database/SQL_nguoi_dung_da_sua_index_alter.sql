    PRIMARY KEY (MaVT, MaQuyen),
    CONSTRAINT FK_VTQUYEN_VAITRO FOREIGN KEY (MaVT) REFERENCES VAITRO(MaVT)
        ON DELETE CASCADE,

    CONSTRAINT FK_VTQUYEN_QUYEN FOREIGN KEY (MaQuyen) REFERENCES PHANQUYEN(MaQuyen)
        ON DELETE CASCADE
);

-- 7. SINH VIÊN

CREATE TABLE SINHVIEN (
    MaSV BIGSERIAL PRIMARY KEY,
    MaNgDung BIGINT UNIQUE,
    MaLop BIGINT NOT NULL,

    CONSTRAINT FK_SINHVIEN_NGUOIDUNG FOREIGN KEY (MaNgDung) REFERENCES NGUOIDUNG(MaNgDung)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_SINHVIEN_LOP FOREIGN KEY (MaLop) REFERENCES LOP(MaLop)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- 8. GIẢNG VIÊN

CREATE TABLE GIANGVIEN (
    MaGV BIGSERIAL PRIMARY KEY,
    MaNgDung BIGINT UNIQUE,
    HocVi NVARCHAR(100),

    CONSTRAINT FK_GIANGVIEN_NGDUNG FOREIGN KEY (MaNgDung) REFERENCES NGUOIDUNG(MaNgDung)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- 9. CÁN BỘ KHOA

CREATE TABLE CANBOKHOA (
