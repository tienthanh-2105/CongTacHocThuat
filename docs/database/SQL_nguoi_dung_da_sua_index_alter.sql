-- 10. QUẢN TRỊ VIÊN

CREATE TABLE QUANTRIVIEN (
    MaQuanTri BIGSERIAL PRIMARY KEY,
    MaNgDung BIGINT UNIQUE,
	MoTa TEXT,

    CONSTRAINT FK_QUANTRI_NGDUNG FOREIGN KEY (MaNgDung) REFERENCES NGUOIDUNG(MaNgDung)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- 11. KẾ HOẠCH HỌC THUẬT

CREATE TABLE KEHOACHHOCTHUAT (
    MaKeHoach BIGSERIAL PRIMARY KEY,
    TenKeHoach NVARCHAR(200) NOT NULL,
    NamHoc VARCHAR(20) NOT NULL,
    HocKy VARCHAR(30),
    TrangThai NVARCHAR(30) NOT NULL DEFAULT 'Dự thảo',
    MaKhoa BIGINT NOT NULL,
    NgPhuTrach BIGINT,

    CONSTRAINT FK_KEHOACH_KHOA FOREIGN KEY (MaKhoa) REFERENCES KHOA(MaKhoa)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_KEHOACH_PHUTRACH FOREIGN KEY (NgPhuTrach) REFERENCES CANBOKHOA(MaCanBo)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT CK_KEHOACH_TRANGTHAI
        CHECK (
            TrangThai IN
            ('Dự thảo', 'Chờ duyệt', 'Cần bổ sung', 'Đã duyệt', 'Không duyệt')
        )
);

-- 12. HOẠT ĐỘNG HỌC THUẬT

CREATE TABLE HOATDONGHOCTHUAT (
    MaHD BIGSERIAL PRIMARY KEY,
    MaKeHoach BIGINT,
    TenHoatDong NVARCHAR(250) NOT NULL,
    MoTa TEXT,
    TgBatDau TIMESTAMP NOT NULL,
    TgKetThuc TIMESTAMP NOT NULL,
    HanDangKy TIMESTAMP,
    DiaDiem NVARCHAR(255),
    SLToiDa INTEGER,
    TrangThai NVARCHAR(30) NOT NULL DEFAULT 'Dự thảo',

    CONSTRAINT FK_HT_KEHOACH FOREIGN KEY (MaKeHoach) REFERENCES KEHOACHHOCTHUAT(MaKeHoach)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT CK_HOATDONG_TG CHECK (TgKetThuc > TgBatDau),

    CONSTRAINT CK_HOATDONG_SOLUONG CHECK (SLToiDa IS NULL OR SLToiDa > 0),

    CONSTRAINT CK_HOATDONG_TRANGTHAI
        CHECK (
            TrangThai IN
            ('Dự thảo', 'Chờ duyệt', 'Đã công bố', 'Đang diễn ra', 'Đã kết thúc', 'Đã hủy')
        )
);

-- 13. CUỘC THI

CREATE TABLE CUOCTHI (
    MaCThi BIGSERIAL PRIMARY KEY,
    MaHD BIGINT UNIQUE NOT NULL,
    TenCuocThi NVARCHAR(250) NOT NULL,
    CapToChuc NVARCHAR(100),
    TheLe TEXT NOT NULL,
    TieuChiCham TEXT,
    SLSinhVien INTEGER,
    HinhThucThi NVARCHAR(30) DEFAULT 'Cá nhân',

    CONSTRAINT FK_CUOCTHI_HOATDG FOREIGN KEY (MaHD) REFERENCES HOATDONGHOCTHUAT(MaHD)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT CK_CUOCTHI_SL CHECK (SLSinhVien IS NULL OR SLSinhVien > 0),

    CONSTRAINT CK_CUOCTHI_HINHTHUC CHECK (HinhThucThi IN ('Cá nhân', 'Theo đội'))
);

-- 14. SEMINAR

CREATE TABLE SEMINAR (
    MaSeminar BIGSERIAL PRIMARY KEY,
    MaHD BIGINT UNIQUE NOT NULL,
    ChuDe NVARCHAR(250) NOT NULL,
    NoiDung TEXT,
    DoiTuongTG TEXT,
    ThoiLuong INTEGER,
    DVChuTri NVARCHAR(200),
    DVPhoiHop NVARCHAR(200),

    CONSTRAINT FK_SEMINAR_HOATDG FOREIGN KEY (MaHD) REFERENCES HOATDONGHOCTHUAT(MaHD)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT CK_SEMINAR_THLUONG CHECK (ThoiLuong IS NULL OR ThoiLuong > 0)
);

-- 15. ĐĂNG KÝ THAM GIA

CREATE TABLE ĐKTHAMGIA (
    MaDK BIGSERIAL PRIMARY KEY,
    MaHD BIGINT NOT NULL,
    MaSV BIGINT NOT NULL,
    NgayDK TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    HinhThuc NVARCHAR(30) NOT NULL,
    NguonDK NVARCHAR(30) NOT NULL DEFAULT 'Sinh viên',
    TrangThai NVARCHAR(30) NOT NULL DEFAULT 'Đã đăng ký',

    CONSTRAINT FK_DANGKY_HOATDG FOREIGN KEY (MaHD) REFERENCES HOATDONGHOCTHUAT(MaHD)
        ON DELETE RESTRICT,

    CONSTRAINT FK_DANGKY_SV FOREIGN KEY (MaSV) REFERENCES SINHVIEN(MaSV)
        ON DELETE RESTRICT,

    CONSTRAINT UQ_DK_SV_HOATDG UNIQUE (MaHD, MaSV),

    CONSTRAINT CK_DK_HINHTHUC CHECK (HinhThuc IN ('Tham gia0', 'Cổ vũ')),

    CONSTRAINT CK_DK_NGUON CHECK (NguonDK IN ('Sinh viên', 'Giảng viên', 'Khoa')),

    CONSTRAINT CK_DK_TRANGTHAI
        CHECK (
            TrangThai IN
            ('Đã đăng ký', 'Đã xác nhận', 'Đã hủy', 'Từ chối')
        )
);

-- 16. PHÂN CÔNG CỔ VŨ

CREATE TABLE PHANCONGCOVU (
    MaCoVu BIGSERIAL PRIMARY KEY,
