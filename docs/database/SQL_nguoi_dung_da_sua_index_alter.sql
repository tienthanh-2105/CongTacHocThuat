    CONSTRAINT FK_CANBO_NGDUNG FOREIGN KEY (MaNgDung) REFERENCES NGUOIDUNG(MaNgDung)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_CANBO_KHOA FOREIGN KEY (MaKhoa) REFERENCES KHOA(MaKhoa)
