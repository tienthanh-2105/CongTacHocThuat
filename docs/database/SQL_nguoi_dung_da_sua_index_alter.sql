-- 17. ĐỀ TÀI

CREATE TABLE DETAI (
    MaDeTai BIGSERIAL PRIMARY KEY,
    MaCThi BIGINT NOT NULL,
    MaDK BIGINT,
    TenDeTai NVARCHAR(250) NOT NULL,
    LinhVuc NVARCHAR(200),
    MoTa TEXT,
    NgBatDau DATE,
    NgKetThuc DATE,
    TrangThai NVARCHAR(30) DEFAULT 'Đang thực hiện',

    CONSTRAINT FK_DETAI_CTHI FOREIGN KEY (MaCThi) REFERENCES CUOCTHI(MaCThi)
