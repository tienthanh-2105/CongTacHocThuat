-- DATABASE: QUẢN LÝ CÔNG TÁC HỌC THUẬT

-- 1. KHOA

CREATE TABLE KHOA (
    MaKhoa BIGSERIAL PRIMARY KEY,
    TenKhoa VARCHAR(100) NOT NULL UNIQUE
);

-- 2. LỚP

CREATE TABLE LOP (
    MaLop BIGSERIAL PRIMARY KEY,
    TenLop NVARCHAR(100) NOT NULL,
    KhoaHoc NVARCHAR(50),
  	MaKhoa BIGINT NOT NULL,

    CONSTRAINT FK_LOP_KHOA
        FOREIGN KEY (MaKhoa)
        REFERENCES KHOA(MaKhoa)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT UQ_LOP_KHOA
        UNIQUE (TenLop, MaKhoa)
);

-- 3. NGƯỜI DÙNG

CREATE TABLE NGUOIDUNG (
    MaNgDung BIGSERIAL PRIMARY KEY,
    HoTen NVARCHAR(150) NOT NULL,
    Email VARCHAR(150) UNIQUE,
    SDT VARCHAR(11),
    NgaySinh DATE,
    GioiTinh NVARCHAR(20),
    TrangThai NVARCHAR(30) NOT NULL DEFAULT 'Hoạt động',

    CONSTRAINT CK_NGDUNG_TRANGTHAI
        CHECK ( TrangThai IN ('Hoạt động', 'Khóa', 'Ngừng hoạt động'))
);

-- 4. VAI TRÒ

CREATE TABLE VAITRO (
    MaVaiTro BIGSERIAL PRIMARY KEY,
    TenVaiTro NVARCHAR(100) NOT NULL UNIQUE
);

-- 5. TÀI KHOẢN

CREATE TABLE TAIKHOAN (
    MaTK BIGSERIAL PRIMARY KEY,
    MaNgDung BIGINT UNIQUE,
    MaVaiTro BIGINT NOT NULL,
    TenDangNhap VARCHAR(100) NOT NULL UNIQUE,
    MatKhau VARCHAR(255) NOT NULL,
    TrangThai NVARCHAR(30) NOT NULL DEFAULT 'Hoạt động',

    CONSTRAINT FK_TAIKHOAN_NGUOIDUNG FOREIGN KEY (MaNgDung) REFERENCES NGUOIDUNG(MaNgDung)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_TAIKHOAN_VAITRO FOREIGN KEY (MaVaiTro) REFERENCES VAITRO(MaVaiTro)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT CK_TAIKHOAN_TRANGTHAI
        CHECK (TrangThai IN ('Hoạt động', 'Khóa', 'Ngừng hoạt động'))
);

-- 6. PHÂN QUYỀN

CREATE TABLE PHANQUYEN (
    MaQuyen BIGSERIAL PRIMARY KEY,
    TenQuyen NVARCHAR(100) NOT NULL UNIQUE,
    MoTa TEXT
);


CREATE TABLE VAITRO_QUYEN (
    MaVT BIGINT NOT NULL,
